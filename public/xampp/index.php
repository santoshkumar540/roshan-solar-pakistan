          <button class="faq-question">How long does NEPRA Net Metering take in Pakistan? <span>▼</span></button>
          <div class="faq-answer">From initial document filing to the green bidirectional meter installation, the complete process takes 18 to 30 working days. Roshan Solar handles the electrical drawings, DISCO inspection, and meter procurement.</div>
        </div>
        <div class="faq-item">
          <button class="faq-question">What is the difference between On-Grid and Hybrid Solar? <span>▼</span></button>
          <div class="faq-answer">On-grid systems export surplus units to the grid but turn off during power outages for safety. Hybrid systems feature lithium (LiFePO4) batteries that seamlessly power your ACs, lights, and appliances with zero interruption during load shedding.</div>
        </div>
        <div class="faq-item">
          <button class="faq-question">How are exported units compensated by DISCO? <span>▼</span></button>
          <div class="faq-answer">Units exported during peak sun are deducted from units consumed at night. Surplus units accumulate as bill credits that roll over or can be monetized under NEPRA rules.</div>
        </div>
      </div>
    </div>
